import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { beforeEach, expect, it, vi } from 'vitest';
import { ReportMailSettings } from './ReportMailSettings';
const api = vi.hoisted(() => ({ fetchPeriodicReport: vi.fn(), savePeriodicReport: vi.fn(), sendPeriodicReportTest: vi.fn() }));
const context = vi.hoisted(() => ({ user: { uid: 'u' }, backendStatus: 'ready', appSession: { store: { id: 's' }, membership: { role: 'OWNER' }, onboardingRequired: false } }));
vi.mock('../section-notices', () => ({ usePhoneLayout: () => false }));
vi.mock('../../context/AppContext', () => ({ useAppContext: () => context }));
vi.mock('../../services/periodic-report-api', () => api);
beforeEach(() => {
  vi.resetAllMocks(); context.appSession.membership.role = 'OWNER';
  api.fetchPeriodicReport.mockResolvedValue({ enabled: false, frequency: 'WEEKLY', sendDay: 1, sendTime: '09:00', recipients: ['owner@test.local'], timezone: 'America/Argentina/Buenos_Aires' });
  api.savePeriodicReport.mockResolvedValue({}); api.sendPeriodicReportTest.mockResolvedValue({ sent: true, message: 'Mail de prueba enviado' });
});
it('loads owner default, submits a draft and preserves errors visibly', async () => {
  render(<ReportMailSettings />);
  const recipient = await screen.findByRole('textbox', { name: 'Mail destinatario' });
  await waitFor(() => expect(recipient).toHaveValue('owner@test.local'));
  await userEvent.click(screen.getByRole('switch'));
  await userEvent.clear(recipient); await userEvent.type(recipient, 'nuevo@test.local');
  await userEvent.click(screen.getAllByRole('button', { name: 'Guardar' })[0]);
  await screen.findByText('Configuración guardada');
  expect(api.savePeriodicReport).toHaveBeenCalledWith(context.user, expect.objectContaining({ enabled: true, recipients: ['nuevo@test.local'], sendDay: 1, sendTime: '09:00' }), expect.any(AbortSignal));
  api.savePeriodicReport.mockRejectedValue(new Error('No se pudo guardar'));
  await userEvent.click(screen.getAllByRole('button', { name: 'Guardar' })[1]);
  expect(await screen.findByRole('alert')).toHaveTextContent('No se pudo guardar');
  expect(recipient).toHaveValue('nuevo@test.local');
});
it('test uses unsaved settings without saving or enabling automatic reports', async () => {
  render(<ReportMailSettings />);
  const button = screen.getByRole('button', { name: 'Enviar mail de prueba' });
  await waitFor(() => expect(button).toBeEnabled());
  await userEvent.click(button);
  expect(await screen.findByRole('status')).toHaveTextContent('Mail de prueba enviado');
  expect(api.sendPeriodicReportTest).toHaveBeenCalledWith(context.user, expect.objectContaining({ enabled: false, frequency: 'WEEKLY' }), expect.any(AbortSignal));
  expect(api.savePeriodicReport).not.toHaveBeenCalled();
  api.sendPeriodicReportTest.mockResolvedValue({ sent: false, message: 'El servidor todavía no puede enviar correos.' });
  await userEvent.click(button);
  expect(await screen.findByRole('alert')).toHaveTextContent('El servidor todavía no puede enviar correos.');
});
it.each(['success', 'failure'])('tests an edited draft without saving and reopens saved settings after %s', async outcome => {
  const view = render(<ReportMailSettings />);
  const button = screen.getByRole('button', { name: 'Enviar mail de prueba' });
  await waitFor(() => expect(button).toBeEnabled());
  await userEvent.click(screen.getByRole('button', { name: 'Mensual' }));
  await userEvent.click(screen.getByRole('switch'));
  const recipient = screen.getByRole('textbox', { name: 'Mail destinatario' });
  await userEvent.clear(recipient); await userEvent.type(recipient, 'draft@test.local');
  fireEvent.change(screen.getByRole('textbox', { name: 'Hora de envío' }), { target: { value: '17:45' } });
  // Neither implicit submit nor sending a test may persist the draft.
  fireEvent.submit(recipient.closest('form')!);
  if (outcome === 'failure') api.sendPeriodicReportTest.mockRejectedValueOnce(new Error('No se pudo enviar el mail de prueba'));
  await userEvent.click(button);
  await screen.findByRole(outcome === 'success' ? 'status' : 'alert');
  expect(api.sendPeriodicReportTest).toHaveBeenCalledWith(context.user, expect.objectContaining({ enabled: true, frequency: 'MONTHLY', sendTime: '17:45', recipients: ['draft@test.local'] }), expect.any(AbortSignal));
  expect(api.savePeriodicReport).not.toHaveBeenCalled();
  await waitFor(() => expect(button).toBeEnabled());
  view.unmount();
  render(<ReportMailSettings />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'Enviar mail de prueba' })).toBeEnabled());
  expect(screen.getByRole('button', { name: 'Semanal' })).toHaveAttribute('aria-pressed', 'true');
  expect(screen.getByRole('textbox', { name: 'Hora de envío' })).toHaveValue('09:00');
  expect(screen.getByRole('textbox', { name: 'Mail destinatario' })).toHaveValue('owner@test.local');
  expect(screen.getByRole('switch')).toHaveAttribute('aria-checked', 'false');
});
it('recovers from a load timeout with an enabled retry and enables the form after reloading', async () => {
  api.fetchPeriodicReport.mockRejectedValueOnce(new DOMException('Timed out', 'TimeoutError'));
  render(<ReportMailSettings />);
  expect(await screen.findByRole('alert')).toHaveTextContent('La solicitud tardó demasiado');
  expect(screen.getByRole('button', { name: 'Enviar mail de prueba' })).toBeDisabled();
  const retry = screen.getByRole('button', { name: 'Reintentar' });
  expect(retry).toBeEnabled();
  await userEvent.click(retry);
  await waitFor(() => expect(screen.getByRole('button', { name: 'Enviar mail de prueba' })).toBeEnabled());
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  expect(screen.getByRole('textbox', { name: 'Mail destinatario' })).toHaveValue('owner@test.local');
  await userEvent.click(screen.getByRole('button', { name: 'Enviar mail de prueba' }));
  expect(await screen.findByRole('status')).toHaveTextContent('Mail de prueba enviado');
});
it('aborts a pending test on exit and ignores its late failure after reopening', async () => {
  let rejectTest!: (error: Error) => void;
  api.sendPeriodicReportTest.mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectTest = reject; }));
  const view = render(<ReportMailSettings />);
  const button = screen.getByRole('button', { name: 'Enviar mail de prueba' });
  await waitFor(() => expect(button).toBeEnabled());
  await userEvent.click(button);
  expect(button).toBeDisabled();
  const signal = api.sendPeriodicReportTest.mock.calls[0][2] as AbortSignal;
  view.unmount();
  expect(signal.aborted).toBe(true);
  render(<ReportMailSettings />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'Enviar mail de prueba' })).toBeEnabled());
  await act(async () => rejectTest(new Error('late failure')));
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  expect(api.savePeriodicReport).not.toHaveBeenCalled();
});
it('aborts a pending load on exit and ignores its late response', async () => {
  let resolveLoad!: (settings: unknown) => void;
  api.fetchPeriodicReport.mockImplementationOnce(() => new Promise(resolve => { resolveLoad = resolve; }));
  const view = render(<ReportMailSettings />);
  const signal = api.fetchPeriodicReport.mock.calls[0][1] as AbortSignal;
  view.unmount();
  expect(signal.aborted).toBe(true);
  render(<ReportMailSettings />);
  await waitFor(() => expect(screen.getByRole('button', { name: 'Enviar mail de prueba' })).toBeEnabled());
  await act(async () => resolveLoad({ enabled: true, frequency: 'MONTHLY', recipients: ['stale@test.local'] }));
  expect(screen.getByRole('textbox', { name: 'Mail destinatario' })).toHaveValue('owner@test.local');
});
it('does not load settings for staff', () => {
  context.appSession.membership.role = 'STAFF'; render(<ReportMailSettings />);
  expect(api.fetchPeriodicReport).not.toHaveBeenCalled(); expect(screen.queryByRole('switch')).not.toBeInTheDocument();
});
