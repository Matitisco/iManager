export type ApplePart = { model: string; capacity: string; color: string };

export function lookupPartNumber(value: string | null | undefined): ApplePart | null {
  const text = (value ?? '').toUpperCase().replace(/\s+/g, '');
  const match = text.match(/^([A-Z][A-Z0-9]{4})(?:[A-Z]{1,3}\/A)?$/);
  if (!match) return null;
  const code = match[1];
  const parts: Readonly<Record<string, readonly [string, string, string]>> = APPLE_PARTS;
  const found = parts[code] ?? (/^[FNP]/.test(code) ? parts[`M${code.slice(1)}`] : undefined);
  if (!found) return null;
  return { model: found[0], capacity: found[1], color: found[2] };
}
