import { expect, test } from '@playwright/test';
import { openDeskSection } from './navigation';
import { authHeaders, bootstrapStoreViaApi, buildTestEmail, createInventoryItemViaApi } from './utils';
const api = process.env.PLAYWRIGHT_API_BASE_URL || 'http://127.0.0.1:3100';
for (const width of [1440, 390]) test(`multiple catalogs keep independent prices at ${width}px @smoke`, async ({ page, request }, info) => {
  await page.setViewportSize({ width, height: 900 });
  const email = buildTestEmail(info, 'multiple-catalogs');
  await bootstrapStoreViaApi(page, request, email, 'Tienda de prueba');
  expect((await request.patch(`${api}/api/stores/current`, { headers: authHeaders(email), data: { currency: 'USD', exchangeMode: 'manual', manualBuy: 1300, manualSell: 1300 } })).ok()).toBeTruthy();
  const item = await createInventoryItemViaApi(request, email, { imei: '359740000000001', model: 'Equipo de prueba', capacity: '128GB', color: 'Negro', condition: 'USADO', grade: 'A', batteryHealth: '95%', cost: 100, price: 200 });
  expect((await request.patch(`${api}/api/catalog/items`, { headers: authHeaders(email), data: { ids: [item.inventoryItem.id], visible: true } })).ok()).toBeTruthy();
  await page.reload();
  await openDeskSection(page, 'publicCatalog');
  await expect(page.getByRole('heading', { name: 'Catálogos', exact: true })).toBeVisible();
  const original = page.getByRole('article', { name: 'Clientes finales' });
  const originalLink = await original.getByRole('link').getAttribute('href');
  await page.getByRole('button', { name: 'Nuevo catálogo' }).click();
  const editor = page.getByRole('dialog', { name: 'Nuevo catálogo' });
  await editor.getByRole('textbox', { name: 'Nombre', exact: true }).fill('Revendedores');
  await editor.getByRole('spinbutton', { name: 'Ajuste sobre el precio' }).fill('-10');
  await editor.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(editor).toBeHidden();
  const reseller = page.getByRole('article', { name: 'Revendedores' });
  await expect(reseller).toContainText('-10 % sobre lista');
  const resellerLink = await reseller.getByRole('link').getAttribute('href');
  expect(resellerLink).not.toBe(originalLink);
  const response = await request.get(`${api}/api/public/catalog/${resellerLink!.split('/c/')[1]}`);
  expect(response.ok()).toBeTruthy(); expect((await response.json()).items[0].price).toBe(180);
  await reseller.getByRole('button', { name: 'Editar ›' }).click();
  const edit = page.getByRole('dialog', { name: 'Revendedores' });
  await edit.getByRole('combobox', { name: 'Regla de precio' }).click();
  await page.getByRole('option', { name: 'Precio por equipo' }).click();
  await edit.getByRole('spinbutton', { name: 'Precio manual de Equipo de prueba 128GB Negro' }).fill('175');
  await edit.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(edit).toBeHidden();
  const manual = await request.get(`${api}/api/public/catalog/${resellerLink!.split('/c/')[1]}`);
  expect((await manual.json()).items[0].price).toBe(175);
  await expect(original.getByRole('link')).toHaveAttribute('href', originalLink!);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await reseller.getByRole('switch').click();
  await expect(reseller.getByRole('switch')).not.toBeChecked();
  const paused = await request.get(`${api}/api/public/catalog/${resellerLink!.split('/c/')[1]}`);
  expect((await paused.json()).active).toBe(false);
});

test('new catalog starts visible and hides only the selected item @smoke', async ({ page, request }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const email = buildTestEmail(info, 'catalog-own-visibility');
  await bootstrapStoreViaApi(page, request, email, 'Tienda ficticia');
  const first = await createInventoryItemViaApi(request, email, { imei: '359740000000011', model: 'Equipo Alfa', capacity: '128GB', color: 'Negro', condition: 'USADO', grade: 'A', batteryHealth: '95%', cost: 100, price: 200 });
  await createInventoryItemViaApi(request, email, { imei: '359740000000012', model: 'Equipo Beta', capacity: '128GB', color: 'Azul', condition: 'USADO', grade: 'A', batteryHealth: '90%', cost: 100, price: 250 });
  // No global publication: OWN must include both without changing those flags.
  await page.reload();
  await openDeskSection(page, 'publicCatalog');
  const add = page.getByRole('button', { name: 'Nuevo catálogo' });
  await expect(add).toBeEnabled();
  await add.click();
  const draft = page.getByRole('dialog', { name: 'Nuevo catálogo' });
  await expect(draft.getByRole('switch', { name: 'Visible en catálogo: Equipo Alfa 128GB' })).toBeChecked();
  await expect(draft.getByRole('switch', { name: 'Visible en catálogo: Equipo Beta 128GB' })).toBeChecked();
  await draft.getByRole('textbox', { name: 'Nombre', exact: true }).fill('Lista propia');
  await draft.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(draft).toBeHidden();
  const row = page.getByRole('article', { name: 'Lista propia' });
  await expect(row.locator('.cat-catalog-count b')).toHaveText('2');
  const link = (await row.getByRole('link').getAttribute('href'))!;
  const publicUrl = `${api}/api/public/catalog/${link.split('/c/')[1]}`;
  const before = await request.get(publicUrl);
  expect(before.ok()).toBeTruthy();
  expect((await before.json()).items).toHaveLength(2);
  await row.getByRole('button', { name: 'Editar ›' }).click();
  const editor = page.getByRole('dialog', { name: 'Lista propia' });
  await editor.getByText('Equipos y visibilidad', { exact: true }).click();
  const toggle = editor.getByRole('switch', { name: 'Visible en catálogo: Equipo Alfa 128GB' });
  await expect(toggle).toBeChecked();
  const saved = page.waitForResponse(response => response.request().method() === 'PATCH' && /\/api\/catalog\/list\/[^/]+\/items$/.test(new URL(response.url()).pathname));
  await toggle.click();
  expect((await saved).ok()).toBeTruthy();
  await expect(toggle).not.toBeChecked();
  const after = await request.get(publicUrl);
  expect((await after.json()).items.map((item: { model: string }) => item.model)).toEqual(['Equipo Beta']);
  const inventory = await request.get(`${api}/api/inventory`, { headers: authHeaders(email) });
  expect((await inventory.json()).inventory.find((item: { id: string }) => item.id === first.inventoryItem.id)).toMatchObject({ catalogVisible: false, catalogNames: [], catalogIncluded: false });
  await editor.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(editor).toBeHidden();
  await expect(row.locator('.cat-catalog-count b')).toHaveText('1');
});
