import { test, expect } from '@playwright/test';
import { mockCommissions } from './fixtures/commissions';

export function commissionsQaTests(phone: boolean) {
 test.describe(phone ? 'issue 334 mobile' : 'issue 334 desktop', () => {
  test('confirms rule actions and voiding; shows deleted-sale deduction and finds devices without Estado', async ({ page }) => {
    const state = await mockCommissions(page, true);
    const navigate = async (hash: string) => page.evaluate(hash => { window.location.hash = hash; }, hash);
    const shot = async (name: string) => {
      await page.evaluate(() => document.fonts.ready);
      await expect(page.locator('.toast')).not.toHaveClass(/show/);
      await page.screenshot({ path: `docs/pr-shots/issue-334-${phone ? 'mobile' : 'desktop'}-${name}.png`, animations: 'disabled', scale: 'css' });
    };
    await navigate('#/comisiones');
    await expect(page.getByText('Cargando comisiones…')).toHaveCount(0);
    await page.getByRole('button', { name: /Martín Gómez/ }).click();
    const detail = page.getByRole('dialog', { name: /^Martín Gómez/ });
    await expect(detail.getByText('A descontar', { exact: true })).toBeVisible();
    await expect(detail.getByText('Eliminada · no genera comisión')).toBeVisible();
    await expect(detail.getByText('US$ 0', { exact: true })).toHaveCount(0);
    await shot('a-descontar');
    await page.getByRole('button', { name: 'Anular pago de US$ 10', exact: true }).click();
    const confirmation = page.getByRole('dialog', { name: 'Anular pago', exact: true });
    await expect(confirmation).toContainText('Quedará en el historial');
    expect(state.voids).toHaveLength(0);
    await shot('void-payment');
    await confirmation.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await expect(detail).toBeVisible();
    await detail.getByRole('button', { name: 'Listo', exact: true }).click();
    await page.getByRole('combobox', { name: 'Mes de comisiones' }).click();
    await page.getByRole('option', { name: 'Noviembre 2026', exact: true }).click();
    await page.getByRole('button', { name: /Martín Gómez/ }).click();
    await expect(page.getByText('Ajuste por venta anulada')).toBeVisible();
    await shot('adjustment-next-month');
    await page.getByRole('button', { name: 'Listo', exact: true }).click();
    await navigate('#/rep');
    await page.getByRole('group', { name: 'Tipo de reporte' }).getByRole('button', { name: 'Comisiones', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Exportar', exact: true })).toBeEnabled();
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar', exact: true }).click();
    const download = await downloaded;
    const { readFile } = await import('node:fs/promises');
    const csv = await readFile((await download.path())!, 'utf8');
    expect(csv.replaceAll("\"'-", '"-')).toContain('"Martín Gómez","0","0","0","0","10","0","-10"');
    await navigate('#/comisiones');
    await expect(page.getByText('Cargando comisiones…')).toHaveCount(0);
    await page.getByRole('button', { name: 'Reglas', exact: true }).first().click();
    await expect(page.getByRole('region', { name: 'Reglas guardadas' })).toBeVisible();
    const teamRule = page.locator('.commission-saved-rule').filter({ hasText: 'Todo el equipo' });
    const openRuleActions = async () => {
      const menu = teamRule.locator('details');
      if (!(await menu.evaluate((node) => (node as HTMLDetailsElement).open))) await menu.locator('summary').click();
    };
    await openRuleActions();
    await shot('rule-actions');
    const deactivate = page.getByRole('button', { name: 'Desactivar regla de Todo el equipo', exact: true });
    await deactivate.click();
    const ruleConfirm = page.getByRole('dialog', { name: 'Desactivar regla', exact: true });
    expect(state.ruleActions).toHaveLength(0);
    await shot('rule-confirm');
    await ruleConfirm.getByRole('button', { name: 'Desactivar regla', exact: true }).click();
    await openRuleActions();
    await expect(page.getByRole('button', { name: 'Activar regla de Todo el equipo', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Activar regla de Todo el equipo', exact: true }).click();
    await page.getByRole('dialog', { name: 'Activar regla', exact: true }).getByRole('button', { name: 'Activar regla', exact: true }).click();
    await openRuleActions();
    await page.getByRole('button', { name: 'Eliminar regla de Todo el equipo', exact: true }).click();
    await page.getByRole('dialog', { name: 'Eliminar regla', exact: true }).getByRole('button', { name: 'Eliminar regla', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Eliminar regla de Todo el equipo', exact: true })).toHaveCount(0);
    await page.getByRole('dialog', { name: 'Regla del equipo', exact: true }).getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.getByRole('button', { name: /Martín Gómez/ }).click();
    await page.getByRole('button', { name: 'Anular pago de US$ 10', exact: true }).click();
    await page.getByRole('dialog', { name: 'Anular pago', exact: true }).getByRole('button', { name: 'Anular pago', exact: true }).click();
    await expect(page.getByText('Pago anulado', { exact: true })).toBeVisible();
    expect(state.voids).toEqual(['payment-martin']);
    await shot('payment-voided');
    await page.getByRole('button', { name: 'Listo', exact: true }).click();
    await navigate('#/ven');
    await page.getByRole('button', { name: 'Registrar venta', exact: true }).click();
    await page.getByRole('combobox', { name: 'Equipo' }).fill('iPhone');
    await expect(page.getByRole('option', { name: /iPhone 15/ })).toBeVisible();
    await page.getByRole('option', { name: /iPhone 15/ }).click();
    await expect(page.getByRole('combobox', { name: 'Equipo' })).toHaveValue('iPhone 15 · 128GB');
    await page.getByRole('dialog', { name: 'Registrar venta', exact: true }).getByRole('button', { name: 'Cerrar', exact: true }).last().click();
    await navigate('#/comisiones');
    await expect(page.getByRole('button', { name: /exportar|descargar|csv/i })).toHaveCount(0);
    state.staff = true;
    await page.reload();
    await expect(page.locator('.desk-app')).toBeVisible();
    await navigate('#/comisiones');
    await expect(page.getByRole('heading', { name: 'Mis comisiones', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: /Anular pago|Reglas|Registrar pago/ })).toHaveCount(0);
  });
});
}
